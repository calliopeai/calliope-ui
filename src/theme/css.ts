import {
  ACCENTS,
  ACCENT_KEYS,
  BASE_SURFACES,
  DEFAULT_ACCENT,
  DENSITIES,
  GROUNDS,
  GROUND_KEYS,
  MODE_TOKENS,
  STATIC_TOKENS,
  SURFACES,
  type Mode,
  type StatusName,
  type Surfaces,
} from "./tokens.js";

type Declarations = readonly (readonly [property: string, value: string])[];

const STATUS_NAMES: StatusName[] = ["success", "warning", "info", "danger"];

function block(selector: string, declarations: Declarations, comment?: string): string {
  const head = comment ? `/* ${comment} */\n` : "";
  const body = declarations.map(([property, value]) => `  ${property}: ${value};`).join("\n");
  return `${head}${selector} {\n${body}\n}`;
}

function surfaceDeclarations(s: Surfaces): Declarations {
  return [
    ["--background", s.background],
    ["--card", s.card],
    ["--popover", s.popover],
    ["--secondary", s.secondary],
    ["--muted", s.muted],
    ["--accent", s.accent],
    ["--muted-foreground", s.mutedForeground],
    ["--border", s.border],
    ["--input", s.input],
    ["--sidebar", s.sidebar === "brand" ? `var(--brand-sidebar, ${s.card})` : s.sidebar],
    ["--sidebar-accent", s.sidebarAccent],
    ["--sidebar-border", s.sidebarBorder],
  ];
}

function modeDeclarations(mode: Mode): Declarations {
  const m = MODE_TOKENS[mode];
  const accent = ACCENTS[DEFAULT_ACCENT];
  return [
    ["color-scheme", mode],
    ...surfaceDeclarations(BASE_SURFACES[mode]),
    ["--foreground", m.foreground],
    ["--card-foreground", m.foreground],
    ["--popover-foreground", m.foreground],
    ["--secondary-foreground", m.foreground],
    ["--accent-foreground", m.foreground],
    ["--brand-primary", mode === "dark" ? accent.dark : accent.light],
    ["--brand-on-primary", mode === "dark" ? accent.onDark : accent.onLight],
    ["--primary", "var(--brand-primary)"],
    ["--primary-foreground", "var(--brand-on-primary)"],
    ["--destructive", m.destructive],
    ["--ring", "var(--brand-primary)"],
    ["--chart-1", "var(--brand-primary)"],
    ...Object.entries(m.chart).map(([key, value]) => [`--${key}`, value] as const),
    ["--sidebar-foreground", m.sidebarForeground],
    ["--sidebar-primary", "var(--brand-primary)"],
    ["--sidebar-primary-foreground", "var(--brand-on-primary)"],
    ["--sidebar-accent-foreground", m.foreground],
    ["--sidebar-ring", "var(--brand-primary)"],
    ["--surface-0", "var(--background)"],
    ["--surface-1", "var(--card)"],
    ["--surface-2", "var(--popover)"],
    ...STATUS_NAMES.flatMap((name) => {
      const s = m.status[name];
      return [
        [`--${name}`, s.base],
        [`--${name}-fg`, s.fg],
        [`--${name}-bg`, s.bg],
        [`--${name}-border`, s.border],
      ] as const;
    }),
  ];
}

/** The accent tokens one accent paints in one mode. */
export function accentDeclarations(
  mode: Mode,
  accent: { dark: string; onDark: string; light: string; onLight: string },
  chart?: Partial<Record<string, string>>
): Declarations {
  return [
    ["--brand-primary", mode === "dark" ? accent.dark : accent.light],
    ["--brand-on-primary", mode === "dark" ? accent.onDark : accent.onLight],
    ...Object.entries(chart ?? {}).map(([key, value]) => [`--${key}`, value ?? ""] as const),
  ];
}

const HEADER = `/*
 * @calliopelabs/ui theme tokens.
 * Generated by \`npm run theme\` from src/theme/tokens.ts. Do not edit by hand.
 *
 * The appearance axes ride on attributes of <html>, set before first paint by
 * AppearanceScript and kept in step by AppearanceProvider:
 *   data-mode     dark | light (follows the ground)
 *   data-ground   the surface ramp
 *   data-accent   a family accent, the product's brand accent, or custom
 *   data-density  compact | cards (any element may carry its own)
 *   --radius      the corners setting, inline
 * Semantic status tokens are defined per mode only: no ground and no accent
 * may change what ok, warn, info or error look like.
 */`;

/** The whole of theme.css. */
export function renderThemeCss(): string {
  const blocks: string[] = [HEADER];

  blocks.push(
    block(
      ":root",
      Object.entries(STATIC_TOKENS).map(([key, value]) => [`--${key}`, value] as const),
      "Mode-independent tokens"
    )
  );

  blocks.push(
    block(
      ':root,\n[data-mode="dark"]',
      modeDeclarations("dark"),
      "Dark: black ground, green accent"
    )
  );
  blocks.push(
    block('[data-mode="light"]', modeDeclarations("light"), "Light: neutral ground, green accent")
  );

  for (const ground of GROUND_KEYS) {
    const { mode, label } = GROUNDS[ground];
    blocks.push(
      block(
        `[data-mode="${mode}"][data-ground="${ground}"]`,
        surfaceDeclarations(SURFACES[ground]),
        `Ground: ${label} (${mode})`
      )
    );
  }

  for (const key of ACCENT_KEYS) {
    const accent = ACCENTS[key];
    const chart: Partial<Record<Mode, Partial<Record<string, string>>>> =
      "chart" in accent ? accent.chart : {};
    for (const mode of ["dark", "light"] as const) {
      blocks.push(
        block(
          `[data-mode="${mode}"][data-accent="${key}"]`,
          accentDeclarations(mode, accent, chart[mode]),
          `Accent: ${accent.label} (${mode})`
        )
      );
    }
  }

  blocks.push(
    block(
      ':root,\n[data-density="compact"]',
      Object.entries(DENSITIES.compact.tokens).map(([key, value]) => [`--${key}`, value] as const),
      `Density: ${DENSITIES.compact.label}, ${DENSITIES.compact.hint.toLowerCase()}`
    )
  );
  blocks.push(
    block(
      '[data-density="cards"]',
      Object.entries(DENSITIES.cards.tokens).map(([key, value]) => [`--${key}`, value] as const),
      `Density: ${DENSITIES.cards.label}, ${DENSITIES.cards.hint.toLowerCase()}`
    )
  );

  return `${blocks.join("\n\n")}\n`;
}

/** The brand tokens a product adds on top of theme.css: its sidebar, and its own accent when it has one. */
export function renderProductCss(product: {
  sidebar: string;
  brandAccent?: {
    key: string;
    dark: string;
    onDark: string;
    light: string;
    onLight: string;
  } | null;
}): string {
  const inline = (selector: string, declarations: Declarations) =>
    `${selector}{${declarations.map(([property, value]) => `${property}:${value}`).join(";")}}`;
  const rules = [inline(":root", [["--brand-sidebar", product.sidebar]])];
  const accent = product.brandAccent;
  if (accent) {
    for (const mode of ["dark", "light"] as const) {
      rules.push(
        inline(
          `[data-mode="${mode}"][data-accent="${accent.key}"]`,
          accentDeclarations(mode, accent)
        )
      );
    }
  }
  return rules.join("");
}
